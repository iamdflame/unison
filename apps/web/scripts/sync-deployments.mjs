/**
 * Bundles the deployment files that exist (devnet, public testnet, mainnet) into a generated module, so a missing
 * network never breaks the build and the browser never touches the filesystem. Runs before dev and build.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../../../deployments/", import.meta.url);
// MAINNET_DEPLOYMENT_FILE points mainnet at a rehearsal on a mainnet fork (e.g. monad-fork-beta.json)
const files = { devnet: "31337.json", testnet: "monad-testnet.json", mainnet: process.env.MAINNET_DEPLOYMENT_FILE ?? "monad-mainnet.json" };
const out = {};
for (const [net, file] of Object.entries(files)) {
  const u = new URL(file, root);
  if (existsSync(u)) out[net] = JSON.parse(readFileSync(u, "utf8"));
}
writeFileSync(
  new URL("../lib/venue/deployments.generated.ts", import.meta.url),
  `/* Generated by scripts/sync-deployments.mjs. Do not edit. */\nimport type { Deployment } from "@unison/sdk";\n\nexport const DEPLOYMENTS: Partial<Record<"devnet" | "testnet" | "mainnet", Deployment>> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`deployments: ${Object.keys(out).join(", ") || "none"}`);
